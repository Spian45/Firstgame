const GLYPH_W = 5;
const GLYPH_H = 7;

export function textWidth(text, scale = 1) {
    return text.length * (GLYPH_W + 1) * scale - scale;
}

function drawRaw(ctx, text, x, y, scale, color) {
    ctx.fillStyle = color;
    let cx = x;
    for (const ch of text) {
        const glyph = GLYPHS[ch] || GLYPHS[ch.toUpperCase()] || GLYPHS['?'];
        for (let row = 0; row < GLYPH_H; row++) {
            const bits = glyph[row];
            for (let col = 0; col < GLYPH_W; col++) {
                if (bits[col] === '1') {
                    ctx.fillRect(cx + col * scale, y + row * scale, scale, scale);
                }
            }
        }
        cx += (GLYPH_W + 1) * scale;
    }
}

// align: 'left' | 'center' | 'right'. shadow draws a 1px dark drop outline
export function drawText(ctx, text, x, y, { scale = 1, color = '#ffffff', align = 'left', shadow = '#140c1c', outline = false } = {}) {
    let dx = Math.round(x);
    const dy = Math.round(y);
    if (align === 'center') dx = Math.round(x - textWidth(text, scale) / 2);
    else if (align === 'right') dx = Math.round(x - textWidth(text, scale));

    if (outline && shadow) {
        for (const [ox, oy] of [[-1, 0], [1, 0], [0, -1], [0, 1], [1, 1]]) {
            drawRaw(ctx, text, dx + ox * scale, dy + oy * scale, scale, shadow);
        }
    } else if (shadow) {
        drawRaw(ctx, text, dx + scale, dy + scale, scale, shadow);
    }
    drawRaw(ctx, text, dx, dy, scale, color);
}

